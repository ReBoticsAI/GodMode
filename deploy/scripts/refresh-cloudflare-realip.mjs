#!/usr/bin/env node
/**
 * Refresh deploy/cloudflare-realip.conf from Cloudflare published IP ranges.
 * Usage: node deploy/scripts/refresh-cloudflare-realip.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "cloudflare-realip.conf");

async function fetchLines(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`GET ${url} failed: ${res.status}`);
  }
  const text = await res.text();
  return text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);
}

const [v4, v6] = await Promise.all([
  fetchLines("https://www.cloudflare.com/ips-v4"),
  fetchLines("https://www.cloudflare.com/ips-v6"),
]);

const today = new Date().toISOString().slice(0, 10);
const lines = [
  "# Cloudflare edge IP ranges for nginx real_ip (CF-Connecting-IP).",
  "# Regenerated by: node deploy/scripts/refresh-cloudflare-realip.mjs",
  "# Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6",
  `# Last refreshed: ${today}`,
  "",
  "# IPv4",
  ...v4.map((cidr) => `set_real_ip_from ${cidr};`),
  "",
  "# IPv6",
  ...v6.map((cidr) => `set_real_ip_from ${cidr};`),
  "",
  "real_ip_header CF-Connecting-IP;",
  "real_ip_recursive on;",
  "",
];

writeFileSync(OUT, lines.join("\n"), "utf8");
console.log(`Wrote ${OUT} (${v4.length} IPv4 + ${v6.length} IPv6 ranges)`);
